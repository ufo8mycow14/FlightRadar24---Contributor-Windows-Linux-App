"""Read-only Windows tests for the offline USB driver planner.

All PnP states and helper arguments are synthetic. These tests never call the
installation helper, change a driver, write a driver to the DriverStore, or
alter Windows certificate stores.
"""
from __future__ import annotations

import base64
import hashlib
import json
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / 'installer' / 'Install-UsbDriver.ps1'
SIGNING_MODEL = 'Microsoft-signed WinUSB.sys; device-specific INF/CAT generated by libwdi'


def encode(value):
    return base64.b64encode(json.dumps(value, separators=(',', ':')).encode('utf-8')).decode('ascii')


def pnp(instance, *, service=None, problem=None, provider=None, status='OK', device_class='USBDevice'):
    return {'InstanceId': instance, 'Class': device_class, 'Status': status,
            'Service': service, 'ProblemCode': problem, 'DriverProvider': provider}


class UsbDriverSetupTests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.powershell = shutil.which('powershell.exe')
        if not cls.powershell:
            raise unittest.SkipTest('Windows PowerShell is required to test the installer script.')

    def run_script(self, *arguments, expected_exit=0):
        command = [self.powershell, '-NoLogo', '-NoProfile', '-NonInteractive',
                   '-ExecutionPolicy', 'Bypass', '-File', str(SCRIPT), *map(str, arguments)]
        result = subprocess.run(command, capture_output=True, timeout=35, text=True,
                                encoding='utf-8', errors='replace', check=False)
        self.assertEqual(result.returncode, expected_exit,
                         f'PowerShell exit={result.returncode}; stderr={result.stderr}; stdout={result.stdout}')
        self.assertTrue(result.stdout.strip(), result.stderr)
        return json.loads(result.stdout.strip())

    def scan(self, devices):
        return self.run_script('-TestDevicesBase64', encode(devices))

    def test_parent_interface_zero_and_nonzero_interface_are_separate(self):
        devices = [
            pnp(r'USB\VID_0BDA&PID_2838\serial-parent', service='usbccgp', problem=0, device_class='USB'),
            pnp(r'USB\VID_0BDA&PID_2838&MI_00\serial-interface0', service='WinUSB', problem=0, provider='libwdi'),
            pnp(r'USB\VID_0BDA&PID_2838&MI_01\serial-interface1', service=None, problem=31, status='Error', device_class=None),
        ]
        report = self.scan(devices)
        self.assertEqual([(item['interface'], item['status']) for item in report['devices']],
                         [(None, 'skipped_parent'), (0, 'ready'), (1, 'skipped_other_interface')])
        text = json.dumps(report)
        for marker in ('serial-parent', 'serial-interface0', 'serial-interface1', 'instance_id'):
            self.assertNotIn(marker, text)

    def test_only_exact_supported_usb_interfaces_can_need_driver(self):
        devices = [
            pnp(r'USB\VID_0BDA&PID_2838&MI_00\missing-class', service=None, problem=28,
                status='Error', device_class=None),
            pnp(r'USB\VID_0BA0&PID_2838&MI_00\unknown-device', service=None, problem=28, status='Error'),
            pnp(r'USB\VID_0BDA&PID_2838&MI_02\interface-two', service=None, problem=28, status='Error'),
        ]
        report = self.scan(devices)
        actionable = [item for item in report['devices'] if item['status'] == 'needs_driver']
        self.assertEqual(len(actionable), 1)
        self.assertEqual(actionable[0]['interface'], 0)
        self.assertIn((2, 'skipped_other_interface'),
                      [(item['interface'], item['status']) for item in report['devices']])
        self.assertEqual(report['ignored_device_count'], 1)

    def test_single_interface_2832_is_supported_but_composite_parents_are_not(self):
        device = pnp(r'USB\VID_0BDA&PID_2832\single', problem=28, status='Error')
        device['CompatibleIds'] = [r'USB\COMPAT_VID_0BDA&Class_FF&SubClass_FF&Prot_FF']
        self.assertEqual(self.scan([device])['devices'][0]['status'], 'needs_driver')
        ready = dict(device, Service='WinUSB', ProblemCode=0, Status='OK')
        self.assertEqual(self.scan([ready])['devices'][0]['status'], 'ready')
        for parent in (dict(device, Service='usbccgp'),
                       dict(device, CompatibleIds=[r'USB\COMPOSITE']),
                       dict(device, Children=['child']),
                       dict(device, CompatibleIds=[]),
                       dict(device, InstanceId=r'USB\VID_0BDA&PID_2838\parent')):
            self.assertEqual(self.scan([parent])['devices'][0]['status'], 'skipped_parent')
        duplicate = dict(device, InstanceId=r'USB\VID_0BDA&PID_2832\another')
        self.assertEqual([x['status'] for x in self.scan([device, duplicate])['devices']],
                         ['manual_required', 'manual_required'])

    def test_single_interface_arguments_never_generate_a_composite_inf(self):
        instance = r'USB\VID_0BDA&PID_2832\single'
        fixture = {'output_directory': r'C:\Temp\driver',
                   'target': {'vid': '0BDA', 'pid': '2832', 'instance_id': instance,
                              'non_composite': True}}
        args = self.run_script('-TestWdiArgumentsBase64', encode(fixture))['arguments']
        self.assertIn('frw-rtl2832.inf', args)
        self.assertEqual(args[-2:], ['--single-interface', '1'])
        self.assertIn(instance, args)

    def test_healthy_winusb_stays_and_duplicate_selector_requires_manual_action(self):
        healthy = pnp(r'USB\VID_0BDA&PID_2838&MI_00\working', service='WinUSB', problem=0)
        missing = pnp(r'USB\VID_0BDA&PID_2838&MI_00\other-device', service=None, problem=28, status='Error')
        report = self.scan([healthy, missing])
        self.assertEqual([item['status'] for item in report['devices']], ['ready', 'manual_required'])
        duplicate = self.scan([missing, dict(missing, InstanceId=r'USB\VID_0BDA&PID_2838&MI_00\second-device')])
        self.assertEqual([item['status'] for item in duplicate['devices']], ['manual_required', 'manual_required'])

    def test_realtek_dvb_binding_is_wrong_driver_but_other_live_driver_is_preserved(self):
        wrong_dvb = pnp(r'USB\VID_0BDA&PID_2838&MI_00\dvb-device', service='RTL2832U', problem=0,
                        provider='Realtek Semiconductor Corp.')
        custom = pnp(r'USB\VID_0BDA&PID_2838&MI_00\custom-device', service='CustomUsb', problem=0,
                     provider='Another vendor')
        winusb_problem = pnp(r'USB\VID_0BDA&PID_2838&MI_00\winusb-problem', service='WinUSB', problem=43,
                             provider='libwdi', status='Error')
        report = self.scan([wrong_dvb])
        self.assertEqual([item['status'] for item in report['devices']], ['needs_driver'])
        report = self.scan([custom, winusb_problem])
        self.assertEqual([item['status'] for item in report['devices']],
                         ['manual_required', 'manual_required'])

    def test_reboot_problem_is_reported_without_calling_helper(self):
        device = pnp(r'USB\VID_0BDA&PID_2838&MI_00\restart-needed', service='WinUSB', problem=14,
                     provider='libwdi', status='Error')
        report = self.scan([device])
        self.assertEqual(report['devices'][0]['status'], 'reboot_required')
        self.assertNotIn('instance_id', json.dumps(report))

    def test_helper_arguments_pin_usb_id_interface_staging_and_exact_instance(self):
        instance = r'USB\VID_0BDA&PID_2838&MI_00\synthetic-test-id'
        fixture = {'output_directory': r'C:\Temp\offline driver stage',
                   'target': {'vid': '0BDA', 'pid': '2838', 'instance_id': instance}}
        result = self.run_script('-TestWdiArgumentsBase64', encode(fixture))
        self.assertEqual(result['arguments'], [
            '-v', '0x0BDA', '-p', '0x2838', '-i', '0', '-t', '0', '-d', r'C:\Temp\offline driver stage',
            '-f', 'frw-rtl2838-mi00.inf', '--instance-id', instance,
        ])

    def test_post_install_verification_requires_the_same_single_interface(self):
        instance = r'USB\VID_0BDA&PID_2838&MI_00\original-device'
        target = {'vid': '0BDA', 'pid': '2838', 'instance_id': instance}
        ready = pnp(instance, service='WinUSB', problem=0)
        unrelated = [
            pnp(r'USB\VID_0BDA&PID_2838\parent', service='usbccgp', problem=0),
            pnp(r'USB\VID_0BDA&PID_2838&MI_01\other-interface', problem=28),
        ]

        def verify(devices):
            return self.run_script('-TestVerificationBase64',
                                   encode({'devices': devices, 'target': target}))['status']

        self.assertEqual(verify([ready, *unrelated]), 'ready')
        self.assertEqual(verify(unrelated), 'unconfirmed')
        swapped = dict(ready, InstanceId=r'USB\VID_0BDA&PID_2838&MI_00\replacement-device')
        self.assertEqual(verify([swapped, *unrelated]), 'unconfirmed')
        self.assertEqual(verify([ready, swapped, *unrelated]), 'unconfirmed')
        self.assertEqual(verify([dict(ready, ProblemCode=14), *unrelated]), 'reboot_required')

    def package_root(self, root, *, signature_required=False, devices=None, helper=b'fixture helper; never executed'):
        root.mkdir(parents=True)
        (root / 'wdi-simple.exe').write_bytes(helper)
        manifest = {
            'schema_version': 1,
            'helper': 'wdi-simple.exe',
            'helper_sha256': hashlib.sha256(helper).hexdigest(),
            'helper_authenticode_required': signature_required,
            'driver_signing_model': SIGNING_MODEL,
            'supported_devices': devices if devices is not None else [
                {'vid': '0x0BDA', 'pid': '0x2838', 'interface': 0}
            ],
        }
        (root / 'manifest.json').write_text(json.dumps(manifest), encoding='utf-8')

    def test_manifest_hash_allowlist_and_signature_policy_fail_closed(self):
        with tempfile.TemporaryDirectory() as directory:
            parent = Path(directory)
            valid = parent / 'valid'
            self.package_root(valid)
            result = self.run_script('-TestPackage', '-DriverRoot', valid)
            self.assertTrue(result['driver_package_available'])
            self.assertIsNone(result['driver_package_error'])

            corrupted = parent / 'corrupted'
            self.package_root(corrupted)
            (corrupted / 'wdi-simple.exe').write_bytes(b'different bytes')
            result = self.run_script('-TestPackage', '-DriverRoot', corrupted)
            self.assertFalse(result['driver_package_available'])
            self.assertIn('SHA-256', result['driver_package_error'])

            broadened = parent / 'broadened'
            self.package_root(broadened, devices=[{'vid': '0BA0', 'pid': '2838', 'interface': 0}])
            result = self.run_script('-TestPackage', '-DriverRoot', broadened)
            self.assertFalse(result['driver_package_available'])
            self.assertIn('unsupported device', result['driver_package_error'])

            missing_interface = parent / 'missing-interface'
            self.package_root(missing_interface, devices=[{'vid': '0BDA', 'pid': '2838'}])
            result = self.run_script('-TestPackage', '-DriverRoot', missing_interface)
            self.assertFalse(result['driver_package_available'])
            self.assertIn('unsupported device', result['driver_package_error'])

            boolean_interface = parent / 'boolean-interface'
            self.package_root(boolean_interface, devices=[{'vid': '0BDA', 'pid': '2838', 'interface': False}])
            result = self.run_script('-TestPackage', '-DriverRoot', boolean_interface)
            self.assertFalse(result['driver_package_available'])
            self.assertIn('unsupported device', result['driver_package_error'])

            unsigned = parent / 'unsigned'
            self.package_root(unsigned, signature_required=True)
            result = self.run_script('-TestPackage', '-DriverRoot', unsigned)
            self.assertFalse(result['driver_package_available'])
            self.assertIn('signature', result['driver_package_error'])

    def test_report_files_match_scan_and_never_include_instance_ids(self):
        with tempfile.TemporaryDirectory() as directory:
            temp = Path(directory)
            report_path = temp / 'usb-report.json'
            summary_path = temp / 'usb-summary.txt'
            device = pnp(r'USB\VID_0BDA&PID_2838&MI_00\secret-serial', service='WinUSB', problem=0)
            report = self.run_script('-TestDevicesBase64', encode([device]),
                                     '-ReportPath', report_path, '-SummaryPath', summary_path)
            saved = json.loads(report_path.read_text(encoding='utf-8'))
            self.assertEqual(saved, report)
            self.assertEqual(saved['devices'][0]['status'], 'ready')
            self.assertIn('ready', summary_path.read_text(encoding='utf-8').lower())
            self.assertNotIn('secret-serial', report_path.read_text(encoding='utf-8'))


if __name__ == '__main__':
    unittest.main(verbosity=2)
