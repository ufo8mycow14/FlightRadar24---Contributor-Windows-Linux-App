"""Build an offline Windows installer from a complete native application package."""
from pathlib import Path
import argparse, hashlib, json, os, subprocess
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT/'src'))
from frw import __version__
DRIVER_SIGNING_MODEL = 'Microsoft-signed WinUSB.sys; device-specific INF/CAT generated by libwdi'
ALLOWED_DEVICES = {('0BDA', '2832', 0), ('0BDA', '2838', 0)}


def validate_driver_manifest(manifest):
    """Reject manifests the bundled PowerShell driver installer cannot safely use."""
    if not isinstance(manifest, dict):
        raise RuntimeError('The offline USB driver manifest must be a JSON object.')
    if (type(manifest.get('schema_version')) is not int or manifest['schema_version'] != 1 or
            manifest.get('helper') != 'wdi-simple.exe'):
        raise RuntimeError('The offline USB driver manifest has an unsupported format.')
    if manifest.get('driver_signing_model') != DRIVER_SIGNING_MODEL:
        raise RuntimeError('The offline USB driver manifest has an unsupported signing model.')
    if type(manifest.get('helper_authenticode_required')) is not bool:
        raise RuntimeError('The offline USB helper Authenticode requirement must be a boolean.')

    helper_hash = manifest.get('helper_sha256')
    if not isinstance(helper_hash, str) or re.fullmatch(r'[0-9a-fA-F]{64}', helper_hash) is None:
        raise RuntimeError('The offline USB driver manifest has an invalid helper SHA-256.')

    devices = manifest.get('supported_devices')
    if not isinstance(devices, list) or not devices:
        raise RuntimeError('The offline USB driver manifest must list supported devices.')
    seen = set()
    for device in devices:
        if not isinstance(device, dict):
            raise RuntimeError('The offline USB driver manifest lists an invalid device.')
        vid = device.get('vid')
        pid = device.get('pid')
        interface = device.get('interface')
        if not isinstance(vid, str) or not isinstance(pid, str) or type(interface) is not int:
            raise RuntimeError('The offline USB driver manifest lists an invalid device.')
        vid = re.sub(r'^0x', '', vid, flags=re.IGNORECASE).upper()
        pid = re.sub(r'^0x', '', pid, flags=re.IGNORECASE).upper()
        identity = (vid, pid, interface)
        if identity not in ALLOWED_DEVICES:
            raise RuntimeError('The offline USB driver manifest lists an unsupported device.')
        if identity in seen:
            raise RuntimeError('The offline USB driver manifest contains duplicate device entries.')
        seen.add(identity)
    return helper_hash


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--package', type=Path, default=ROOT/'work/package/FlightRadar24')
    parser.add_argument('--output', type=Path, default=ROOT/'work/installer-dist')
    parser.add_argument('--iscc', type=Path, required=True, help='Inno Setup 6 compiler executable')
    parser.add_argument('--version', default=__version__)
    parser.add_argument('--public-release', action='store_true',
                        help='Exclude the proprietary feeder; offer a verified vendor download during setup')
    args = parser.parse_args()
    package = args.package.resolve()
    if args.public_release and (package/'runtime/feeder/fr24feed').exists():
        raise RuntimeError('Public packages must not contain the proprietary feeder executable.')
    drivers = package/'runtime/drivers/winusb'
    required = ('FlightRadar24.exe', 'runtime/decoder/dump1090.exe',
                'runtime/drivers/winusb/manifest.json', 'runtime/drivers/winusb/wdi-simple.exe')
    for relative_path in required:
        if not (package/relative_path).is_file():
            raise RuntimeError('The application package is incomplete: '+relative_path)
    manifest = json.loads((drivers/'manifest.json').read_text(encoding='utf-8'))
    pinned_hash = validate_driver_manifest(manifest)
    helper = drivers/'wdi-simple.exe'
    digest = hashlib.sha256(helper.read_bytes()).hexdigest()
    if digest.lower() != pinned_hash.lower():
        raise RuntimeError('The offline USB helper does not match its pinned SHA-256.')
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    command = [str(args.iscc.resolve()), '/DAppSource='+str(package), '/DSetupOutput='+str(output),
               '/DAppVersion='+args.version, str(ROOT/'installer/FlightRadar24.iss')]
    if args.public_release:
        command.insert(-1, '/DPublicRelease=1')
    compiled = subprocess.run(command, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                              text=True, encoding='utf-8', errors='replace',
                              creationflags=0x08000000 if os.name == 'nt' else 0)
    print(compiled.stdout, end='', flush=True)
    compiled.check_returncode()
    setup = output/f'FlightRadar24-{args.version}-Windows-x64-Setup.exe'
    if not setup.is_file():
        raise RuntimeError('Inno Setup did not produce the expected installer.')
    print(json.dumps({'installer': str(setup), 'bytes': setup.stat().st_size,
                      'sha256': hashlib.sha256(setup.read_bytes()).hexdigest(),
                      'offline_driver_helper_sha256': digest}, indent=2))


if __name__ == '__main__':
    main()
