[CmdletBinding()]
param(
    [switch]$Install,
    [switch]$Scan,
    [string]$DriverRoot,
    [string]$ReportPath,
    [string]$SummaryPath,
    [string]$TestDevicesBase64,
    [string]$TestWdiArgumentsBase64,
    [string]$TestVerificationBase64,
    [switch]$TestPackage
)

# Read-only inventory is the default. This script only offers USB interface 0
# for the two Realtek RTL2832 IDs that the bundled librtlsdr recognizes.
$ErrorActionPreference = 'Stop'
$AllowedIds = @('0BDA:2832:00', '0BDA:2838:00')
$SigningModel = 'Microsoft-signed WinUSB.sys; device-specific INF/CAT generated by libwdi'

function Get-DevicePropertyValue($Properties, [string]$Name) {
    $property = $Properties | Where-Object { $_.KeyName -eq $Name } | Select-Object -First 1
    if ($null -eq $property) { return $null }
    return $property.Data
}

function Get-InventoryFromDevices([object[]]$Devices) {
    $records = @()
    $ignored = 0
    foreach ($device in $Devices) {
        $instanceId = [string]$device.InstanceId
        # Keep the full PnP path inside this process only. It can contain a
        # hardware serial, so reports only include VID/PID/interface fields.
        $match = [regex]::Match($instanceId, '^USB\\VID_([0-9A-F]{4})&PID_([0-9A-F]{4})(?:&MI_([0-9A-F]{2}))?(?:\\|$)', 'IgnoreCase')
        if (-not $match.Success) { $ignored++; continue }
        $vid = $match.Groups[1].Value.ToUpperInvariant()
        $productId = $match.Groups[2].Value.ToUpperInvariant()
        $mi = if ($match.Groups[3].Success) { $match.Groups[3].Value.ToUpperInvariant() } else { $null }
        $identity = '{0}:{1}:{2}' -f $vid, $productId, $(if ($null -eq $mi) { 'PARENT' } else { $mi })
        $rtlProduct = ('{0}:{1}' -f $vid,$productId) -in @('0BDA:2832','0BDA:2838')
        if (-not $rtlProduct) { $ignored++; continue }

        $singleInterface = $null -eq $mi -and $productId -eq '2832' -and
            [string]$device.Service -ne 'usbccgp' -and
            @($device.CompatibleIds | Where-Object { $_ -match '^USB\\(?:COMPAT_VID_0BDA&)?Class_FF(?:&|$)' }).Count -gt 0 -and
            @($device.CompatibleIds | Where-Object { $_ -eq 'USB\COMPOSITE' }).Count -eq 0 -and
            @($device.Children | Where-Object { $_ }).Count -eq 0
        if ($singleInterface) { $mi = '00'; $identity = '{0}:{1}:00' -f $vid,$productId }
        if ($null -eq $mi) {
            $records += [pscustomobject]@{ vid=$vid; pid=$productId; interface=$null; status='skipped_parent'; reason='Composite parent is managed by Windows.'; service=[string]$device.Service; problem_code=$null; driver_provider=$null }
            continue
        }
        if ($mi -ne '00') {
            $records += [pscustomobject]@{ vid=$vid; pid=$productId; interface=([Convert]::ToInt32($mi, 16)); status='skipped_other_interface'; reason='Only interface 0 is supported.'; service=[string]$device.Service; problem_code=$null; driver_provider=$null }
            continue
        }
        if ($AllowedIds -notcontains $identity) { $ignored++; continue }

        $service = [string]$device.Service
        $provider = [string]$device.DriverProvider
        $problemValue = $device.ProblemCode
        if ($null -eq $problemValue -and $null -ne $device.Problem) { $problemValue = $device.Problem }
        $problem = 0
        if ($null -ne $problemValue -and [string]$problemValue -ne '') {
            try { $problem = [int]$problemValue } catch { $problem = 0 }
        }
        if ($service -eq 'WinUSB' -and $problem -eq 0) {
            $status = 'ready'; $reason = 'WinUSB is already bound and the interface reports no PnP problem.'
        } elseif ($problem -eq 14) {
            $status = 'reboot_required'; $reason = 'Windows reports that a restart is required before driver changes.'
        } elseif ($service -eq 'WinUSB') {
            # A broken/disabled WinUSB device can have a different cause than a
            # missing driver. Do not run a helper that will refuse this binding.
            $status = 'manual_required'; $reason = 'WinUSB is bound but Windows reports a PnP problem; setup will not replace it.'
        } elseif ($service -and $problem -eq 0 -and $provider -match '(?i)realtek|rtl2832|dvb') {
            # A Realtek DVB driver binds to the same data interface but is not the
            # WinUSB binding required by librtlsdr. It is the sole healthy-driver
            # replacement case covered by the package's exact VID/PID allowlist.
            $status = 'needs_driver'; $reason = 'A Realtek DVB driver is bound; this receiver needs WinUSB.'
        } elseif ($service -and $problem -eq 0) {
            $status = 'manual_required'; $reason = 'A different working driver is bound; setup will not replace it.'
        } elseif ($problem -in @(1, 28, 31) -or (-not $service -and [string]$device.Status -eq 'Error')) {
            $status = 'needs_driver'; $reason = 'The supported interface has no working WinUSB binding.'
        } elseif (-not $service -and $problem -eq 0) {
            $status = 'needs_driver'; $reason = 'The supported interface has no WinUSB service binding.'
        } else {
            $status = 'manual_required'; $reason = 'The interface state is unclear; setup will not change its driver.'
        }
        $records += [pscustomobject]@{ vid=$vid; pid=$productId; interface=0; non_composite=$singleInterface; status=$status; reason=$reason; service=$service; problem_code=$problem; driver_provider=$provider; instance_id=$instanceId }
    }

    # libwdi's VID/PID/interface selector cannot distinguish two attached
    # devices with identical IDs. Never run it if any matching ID has a
    # healthy binding or if more than one matching interface is present.
    foreach ($group in ($records | Where-Object { $_.interface -eq 0 } | Group-Object { '{0}:{1}:00' -f $_.vid,$_.pid })) {
        if ($group.Count -gt 1 -and @($group.Group | Where-Object { $_.status -eq 'needs_driver' }).Count -gt 0) {
            foreach ($record in $group.Group) {
                if ($record.status -eq 'needs_driver') {
                    $record.status = 'manual_required'
                    $record.reason = 'Multiple devices share this VID/PID/interface; setup cannot select one safely.'
                }
            }
        }
    }
    return [pscustomobject]@{ devices=@($records); ignored_count=$ignored }
}

function Get-LiveInventory {
    $devices = @(Get-PnpDevice -PresentOnly | ForEach-Object {
        $pnpDevice = $_
        # Class may be null or a media-specific class while a driver is missing.
        # Restrict property reads to the supported USB IDs, regardless of class.
        if ([string]$pnpDevice.InstanceId -notmatch '^USB\\VID_0BDA&PID_(2832|2838)(?:&MI_[0-9A-F]{2})?(?:\\|$)') { return }
        $properties = @(Get-PnpDeviceProperty -InstanceId $pnpDevice.InstanceId -ErrorAction SilentlyContinue)
        $service = Get-DevicePropertyValue $properties 'DEVPKEY_Device_Service'
        $provider = Get-DevicePropertyValue $properties 'DEVPKEY_Device_DriverProvider'
        $problem = Get-DevicePropertyValue $properties 'DEVPKEY_Device_ProblemCode'
        $compatible = Get-DevicePropertyValue $properties 'DEVPKEY_Device_CompatibleIds'
        $children = Get-DevicePropertyValue $properties 'DEVPKEY_Device_Children'
        [pscustomobject]@{ Class=$pnpDevice.Class; Status=[string]$pnpDevice.Status; InstanceId=$pnpDevice.InstanceId; Service=$service; DriverProvider=$provider; ProblemCode=$problem; CompatibleIds=$compatible; Children=$children }
    })
    return Get-InventoryFromDevices $devices
}

function Get-TargetBindingStatus($Inventory, $Target) {
    $matches = @($Inventory.devices | Where-Object {
        $_.interface -eq 0 -and $_.vid -eq $Target.vid -and $_.pid -eq $Target.pid
    })
    if ($matches.Count -ne 1 -or $matches[0].instance_id -ne $Target.instance_id) {
        return 'unconfirmed'
    }
    return [string]$matches[0].status
}

function Get-DriverPackage([string]$Root) {
    if (-not (Test-Path -LiteralPath $Root -PathType Container)) {
        return [pscustomobject]@{ available=$false; error='Bundled USB driver support files are missing.'; helper=$null; supported_ids=@() }
    }
    $manifestPath = Join-Path $Root 'manifest.json'
    if (-not (Test-Path -LiteralPath $manifestPath -PathType Leaf)) {
        return [pscustomobject]@{ available=$false; error='Bundled USB driver manifest is missing.'; helper=$null; supported_ids=@() }
    }
    try { $manifest = Get-Content -LiteralPath $manifestPath -Raw | ConvertFrom-Json } catch {
        return [pscustomobject]@{ available=$false; error='Bundled USB driver manifest is invalid.'; helper=$null; supported_ids=@() }
    }
    if ($manifest.schema_version -ne 1 -or $manifest.helper -ne 'wdi-simple.exe' -or
        $manifest.helper_sha256 -notmatch '^[0-9a-fA-F]{64}$' -or
        $manifest.driver_signing_model -ne $SigningModel -or
        $manifest.helper_authenticode_required -isnot [bool] -or
        $manifest.supported_devices -isnot [array]) {
        return [pscustomobject]@{ available=$false; error='Bundled USB driver manifest failed validation.'; helper=$null; supported_ids=@() }
    }
    $supported = @()
    foreach ($entry in $manifest.supported_devices) {
        $manifestVid = ([string]$entry.vid) -replace '^0x',''
        $manifestPid = ([string]$entry.pid) -replace '^0x',''
        $interfaceProperty = $entry.PSObject.Properties['interface']
        $interfaceValue = if ($null -ne $interfaceProperty) { $interfaceProperty.Value } else { $null }
        $interfaceIsZero = $null -ne $interfaceValue -and
            $interfaceValue -isnot [bool] -and
            ($interfaceValue -is [byte] -or $interfaceValue -is [int16] -or
             $interfaceValue -is [int32] -or $interfaceValue -is [int64]) -and
            $interfaceValue -eq 0
        if ($manifestVid -notmatch '^[0-9A-Fa-f]{4}$' -or $manifestPid -notmatch '^[0-9A-Fa-f]{4}$' -or -not $interfaceIsZero) {
            return [pscustomobject]@{ available=$false; error='Bundled USB driver manifest lists an unsupported device.'; helper=$null; supported_ids=@() }
        }
        $id = ('{0}:{1}:00' -f $manifestVid.ToUpperInvariant(),$manifestPid.ToUpperInvariant())
        if ($AllowedIds -notcontains $id) {
            return [pscustomobject]@{ available=$false; error='Bundled USB driver manifest lists an unsupported device.'; helper=$null; supported_ids=@() }
        }
        if ($supported -contains $id) {
            return [pscustomobject]@{ available=$false; error='Bundled USB driver manifest contains duplicate device entries.'; helper=$null; supported_ids=@() }
        }
        $supported += $id
    }
    $helper = Join-Path $Root 'wdi-simple.exe'
    if (-not (Test-Path -LiteralPath $helper -PathType Leaf)) {
        return [pscustomobject]@{ available=$false; error='Bundled USB driver helper is missing.'; helper=$null; supported_ids=$supported }
    }
    # Avoid relying on the optional PowerShell utility module being imported in
    # installer-hosted sessions; the framework crypto API is available there.
    $sha256 = [System.Security.Cryptography.SHA256]::Create()
    try {
        $stream = [IO.File]::OpenRead($helper)
        try { $actualHash = ([BitConverter]::ToString($sha256.ComputeHash($stream))).Replace('-', '') }
        finally { $stream.Dispose() }
    } finally { $sha256.Dispose() }
    if (-not [string]::Equals($actualHash, $manifest.helper_sha256, [StringComparison]::OrdinalIgnoreCase)) {
        return [pscustomobject]@{ available=$false; error='Bundled USB driver helper failed its SHA-256 check.'; helper=$null; supported_ids=$supported }
    }
    if ($manifest.helper_authenticode_required) {
        if (-not (Get-Command Get-AuthenticodeSignature -ErrorAction SilentlyContinue)) {
            return [pscustomobject]@{ available=$false; error='Bundled USB driver helper signature could not be checked.'; helper=$null; supported_ids=$supported }
        }
        $signature = Get-AuthenticodeSignature -LiteralPath $helper
        if ($signature.Status -ne 'Valid') {
            return [pscustomobject]@{ available=$false; error='Bundled USB driver helper signature is not valid.'; helper=$null; supported_ids=$supported }
        }
    }
    return [pscustomobject]@{ available=($supported.Count -gt 0); error=$null; helper=$helper; supported_ids=$supported; single_interface_2832=($manifest.single_interface_2832 -is [bool] -and $manifest.single_interface_2832) }
}

function Write-SetupReport($Report) {
    if ($null -ne $Report.devices) {
        $Report.devices = @($Report.devices | ForEach-Object {
            [pscustomobject]@{ vid=$_.vid; pid=$_.pid; interface=$_.interface; status=$_.status; reason=$_.reason; service=$_.service; problem_code=$_.problem_code; driver_provider=$_.driver_provider }
        })
    }
    $json = $Report | ConvertTo-Json -Depth 8 -Compress
    Write-Output $json
    if ($ReportPath) {
        if (-not [IO.Path]::IsPathRooted($ReportPath)) { throw 'The USB driver report path must be absolute.' }
        [IO.File]::WriteAllText($ReportPath, $json, (New-Object System.Text.UTF8Encoding($false)))
    }
    if ($SummaryPath) {
        if (-not [IO.Path]::IsPathRooted($SummaryPath)) { throw 'The USB driver summary path must be absolute.' }
        $summary = switch ([string]$Report.outcome) {
            'ready' { 'RTL-SDR USB interface 0 is ready with WinUSB.'; break }
            'no_install_needed' { if (@($Report.devices).Count -gt 0) { 'No USB driver changes were needed.' } else { 'No supported RTL-SDR was connected; setup made no driver changes.' }; break }
            'manual_required' { 'Some receiver interfaces need attention. Review Windows Device Manager and the setup report.'; break }
            'reboot_required' { 'Restart Windows to finish the USB driver installation.'; break }
            'failed' { 'The offline USB driver installation could not be confirmed. Review the setup report.'; break }
            default { if (@($Report.devices | Where-Object { $_.status -eq 'ready' }).Count -gt 0) { 'RTL-SDR USB interface 0 is ready with WinUSB.' } elseif (@($Report.devices | Where-Object { $_.status -eq 'needs_driver' }).Count -gt 0) { 'A supported RTL-SDR needs its WinUSB driver.' } else { 'No supported RTL-SDR needs a driver change.' }; break }
        }
        [IO.File]::WriteAllText($SummaryPath, [string]$summary, (New-Object System.Text.UTF8Encoding($false)))
    }
}

function ConvertTo-Win32Argument([string]$Argument) {
    if ($Argument -notmatch '[\s"]') { return $Argument }
    $builder = New-Object System.Text.StringBuilder
    [void]$builder.Append('"')
    $slashes = 0
    foreach ($character in $Argument.ToCharArray()) {
        if ($character -eq [char]'\') { $slashes++; continue }
        if ($character -eq [char]'"') {
            [void]$builder.Append(('\' * (($slashes * 2) + 1)))
            [void]$builder.Append('"')
            $slashes = 0
            continue
        }
        if ($slashes) { [void]$builder.Append(('\' * $slashes)); $slashes = 0 }
        [void]$builder.Append($character)
    }
    if ($slashes) { [void]$builder.Append(('\' * ($slashes * 2))) }
    [void]$builder.Append('"')
    return $builder.ToString()
}

function Get-WdiArguments($Target, [string]$OutputDirectory) {
    if ($Target.non_composite) {
        return [string[]]@('-v','0x0BDA','-p','0x2832','-i','0','-t','0','-d',$OutputDirectory,'-f','frw-rtl2832.inf','--instance-id',$Target.instance_id,'--single-interface','1')
    }
    $infName = if ($Target.pid -eq '2838') { 'frw-rtl2838-mi00.inf' } else { 'frw-rtl2832-mi00.inf' }
    $vendor = '0x{0}' -f $Target.vid
    $product = '0x{0}' -f $Target.pid
    return [string[]]@('-v',$vendor,'-p',$product,'-i','0','-t','0','-d',$OutputDirectory,'-f',$infName,'--instance-id',$Target.instance_id)
}

function Remove-SafeStagingDirectory([string]$Directory) {
    if (-not $Directory) { return }
    $tempRoot = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd([char[]]@([IO.Path]::DirectorySeparatorChar,[IO.Path]::AltDirectorySeparatorChar))
    $resolved = [IO.Path]::GetFullPath($Directory)
    $withinTemp = $resolved.StartsWith(($tempRoot+[IO.Path]::DirectorySeparatorChar), [StringComparison]::OrdinalIgnoreCase)
    if ($withinTemp -and (Test-Path -LiteralPath $resolved -PathType Container)) {
        Remove-Item -LiteralPath $resolved -Recurse -Force -ErrorAction SilentlyContinue
    }
}

function Invoke-DriverHelper($Package, $Target) {
    $nativeMachine = [System.Environment]::GetEnvironmentVariable('PROCESSOR_ARCHITEW6432')
    if (-not $nativeMachine) { $nativeMachine = [System.Environment]::GetEnvironmentVariable('PROCESSOR_ARCHITECTURE') }
    if ($nativeMachine -ne 'AMD64') { return [pscustomobject]@{ status='failed'; error='The bundled USB driver helper supports 64-bit Intel/AMD Windows only.' } }
    $principal = New-Object Security.Principal.WindowsPrincipal([Security.Principal.WindowsIdentity]::GetCurrent())
    if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
        return [pscustomobject]@{ status='failed'; error='Administrator privileges are required to install a Windows USB driver.' }
    }
    $id = ('{0}:{1}:00' -f $Target.vid,$Target.pid)
    if ($Package.supported_ids -notcontains $id) { return [pscustomobject]@{ status='failed'; error='The bundled driver does not support this USB interface.' } }
    if ($Target.non_composite -and -not $Package.single_interface_2832) { return [pscustomobject]@{ status='failed'; error='This single-interface RTL2832U needs an updated offline driver helper.' } }

    # Recheck the exact instance before launching because PnP state can change.
    # The instance ID remains internal and is never written to setup reports.
    $fresh = Get-LiveInventory
    $matches = @($fresh.devices | Where-Object { $_.interface -eq 0 -and ('{0}:{1}:00' -f $_.vid,$_.pid) -eq $id })
    $unhealthy = @($matches | Where-Object { $_.status -eq 'needs_driver' })
    $healthy = @($matches | Where-Object { $_.status -eq 'ready' })
    if ($matches.Count -ne 1 -or $unhealthy.Count -ne 1 -or $healthy.Count -gt 0 -or $unhealthy[0].instance_id -ne $Target.instance_id) {
        return [pscustomobject]@{ status='manual_required'; error='USB device state changed or is ambiguous; no driver was installed.' }
    }

    $outDirectory = Join-Path ([System.IO.Path]::GetTempPath()) ('frw-usb-'+[guid]::NewGuid().ToString('N'))
    $tempRoot = [IO.Path]::GetFullPath([IO.Path]::GetTempPath()).TrimEnd([char[]]@([IO.Path]::DirectorySeparatorChar,[IO.Path]::AltDirectorySeparatorChar))
    $outFullPath = [IO.Path]::GetFullPath($outDirectory)
    $withinTemp = $outFullPath.StartsWith(($tempRoot+[IO.Path]::DirectorySeparatorChar), [StringComparison]::OrdinalIgnoreCase)
    if (-not $withinTemp) { return [pscustomobject]@{ status='failed'; error='The temporary USB driver staging path is outside the Windows temporary directory.' } }
    [void](New-Item -ItemType Directory -Path $outDirectory -Force)
    # Type 0 selects WinUSB. libwdi generates the device INF and CAT locally;
    # this uses normal Windows signature verification without stealth options.
    $arguments = Get-WdiArguments $Target $outDirectory
    $process = $null
    try {
        $startInfo = New-Object System.Diagnostics.ProcessStartInfo
        $startInfo.FileName = $Package.helper
        $startInfo.Arguments = (($arguments | ForEach-Object { ConvertTo-Win32Argument ([string]$_) }) -join ' ')
        $startInfo.UseShellExecute = $false
        $startInfo.CreateNoWindow = $true
        $startInfo.WindowStyle = [System.Diagnostics.ProcessWindowStyle]::Hidden
        $process = [System.Diagnostics.Process]::Start($startInfo)
        if (-not $process.WaitForExit(120000)) {
            # The helper may be waiting for a Windows confirmation, and its
            # elevated installer child may still be active. Keep both the
            # process and staging intact until Windows finishes that action.
            return [pscustomobject]@{ status='failed'; error='USB driver helper is still running after the timeout. Review Windows prompts and device state; installation completion is unconfirmed.' }
        }
        if ($process.ExitCode -ne 0) { return [pscustomobject]@{ status='failed'; error=('USB driver helper returned exit code {0}.' -f $process.ExitCode) } }
    } catch {
        return [pscustomobject]@{ status='failed'; error='USB driver helper could not complete the installation.' }
    } finally {
        if ($process) { $process.Dispose() }
    }

    # A successful helper exit alone does not prove that PnP now uses WinUSB.
    for ($attempt = 0; $attempt -lt 6; $attempt++) {
        Start-Sleep -Milliseconds 500
        $after = Get-LiveInventory
        $currentStatus = Get-TargetBindingStatus $after $Target
        if ($currentStatus -eq 'ready') { return [pscustomobject]@{ status='ready'; error=$null; staging_dir=$outFullPath } }
        if ($currentStatus -eq 'reboot_required') {
            return [pscustomobject]@{ status='reboot_required'; error='Windows reports that a restart is required to finish installing the USB driver.'; staging_dir=$outFullPath }
        }
    }
    return [pscustomobject]@{ status='failed'; error='Windows did not confirm a working WinUSB binding after installation.'; staging_dir=$outFullPath }
}

try {
    if (-not $DriverRoot) { $DriverRoot = Join-Path $PSScriptRoot '..\runtime\drivers\winusb' }
    if ($TestVerificationBase64) {
        $fixtureBytes = [Convert]::FromBase64String($TestVerificationBase64)
        $fixture = [System.Text.Encoding]::UTF8.GetString($fixtureBytes) | ConvertFrom-Json
        $inventory = Get-InventoryFromDevices @($fixture.devices)
        $verification = Get-TargetBindingStatus $inventory $fixture.target
        Write-SetupReport ([pscustomobject]@{ mode='test_verification'; status=$verification })
        exit 0
    }
    if ($TestDevicesBase64 -or $TestPackage) {
        $devices = @()
        $ignoredCount = 0
        if ($TestDevicesBase64) {
        $fixtureBytes = [Convert]::FromBase64String($TestDevicesBase64)
        $fixture = [System.Text.Encoding]::UTF8.GetString($fixtureBytes) | ConvertFrom-Json
        $inventory = Get-InventoryFromDevices @($fixture)
            $devices = $inventory.devices
            $ignoredCount = $inventory.ignored_count
        }
        $package = Get-DriverPackage $DriverRoot
        $report = [pscustomobject]@{ mode='test'; driver_package_available=$package.available; driver_package_error=$package.error; ignored_device_count=$ignoredCount; devices=$devices }
        Write-SetupReport $report
        exit 0
    }
    if ($TestWdiArgumentsBase64) {
        $fixtureBytes = [Convert]::FromBase64String($TestWdiArgumentsBase64)
        $fixture = [System.Text.Encoding]::UTF8.GetString($fixtureBytes) | ConvertFrom-Json
        $arguments = Get-WdiArguments $fixture.target ([string]$fixture.output_directory)
        $report = [pscustomobject]@{ mode='test_arguments'; arguments=$arguments }
        Write-SetupReport $report
        exit 0
    }

    $inventory = Get-LiveInventory
    $package = Get-DriverPackage $DriverRoot
    $initialState = if ($Install) { 'install' } else { 'scan' }
    if (-not $Install) {
        $report = [pscustomobject]@{ mode=$initialState; driver_package_available=$package.available; driver_package_error=$package.error; driver_signing_model=$SigningModel; ignored_device_count=$inventory.ignored_count; devices=$inventory.devices }
        Write-SetupReport $report
        exit 0
    }

    $targets = @($inventory.devices | Where-Object { $_.status -eq 'needs_driver' })
    $manual = @($inventory.devices | Where-Object { $_.status -eq 'manual_required' })
    $reboot = @($inventory.devices | Where-Object { $_.status -eq 'reboot_required' })
    if ($targets.Count -eq 0) {
        $result = if ($manual.Count -gt 0) { 'manual_required' } elseif ($reboot.Count -gt 0) { 'reboot_required' } else { 'no_install_needed' }
        $report = [pscustomobject]@{ mode='install'; outcome=$result; driver_package_available=$package.available; driver_package_error=$package.error; driver_signing_model=$SigningModel; ignored_device_count=$inventory.ignored_count; devices=$inventory.devices }
        Write-SetupReport $report
        if ($manual.Count -gt 0) { exit 1 }
        if ($reboot.Count -gt 0) { exit 3010 }
        exit 0
    }
    if ($targets.Count -ne 1) {
        foreach ($target in $targets) { $target.status='manual_required'; $target.reason='More than one USB interface needs a driver; setup will not choose one.' }
        $report = [pscustomobject]@{ mode='install'; outcome='manual_required'; driver_package_available=$package.available; driver_package_error=$package.error; driver_signing_model=$SigningModel; ignored_device_count=$inventory.ignored_count; devices=$inventory.devices }
        Write-SetupReport $report
        exit 1
    }
    if (-not $package.available) {
        $targets[0].status='failed'; $targets[0].reason=$package.error
        $report = [pscustomobject]@{ mode='install'; outcome='failed'; driver_package_available=$false; driver_package_error=$package.error; driver_signing_model=$SigningModel; ignored_device_count=$inventory.ignored_count; devices=$inventory.devices }
        Write-SetupReport $report
        exit 1
    }

    $helperResult = Invoke-DriverHelper $package $targets[0]
    $finalInventory = Get-LiveInventory
    $finalStatus = Get-TargetBindingStatus $finalInventory $targets[0]
    if ($helperResult.status -eq 'reboot_required') {
        $outcome='reboot_required'; $targets[0].status='reboot_required'; $targets[0].reason=$helperResult.error
    } elseif ($helperResult.status -eq 'manual_required') {
        $outcome='manual_required'; $targets[0].status='manual_required'; $targets[0].reason=$helperResult.error
    } elseif ($helperResult.status -eq 'failed') {
        $outcome='failed'; $targets[0].status='failed'; $targets[0].reason=$helperResult.error
    } elseif ($helperResult.status -eq 'ready' -and $finalStatus -eq 'ready') {
        $outcome='ready'
        foreach ($index in 0..($inventory.devices.Count-1)) {
            if ($inventory.devices[$index].vid -eq $targets[0].vid -and $inventory.devices[$index].pid -eq $targets[0].pid -and $inventory.devices[$index].interface -eq 0) {
                $inventory.devices[$index].status='ready'
                $inventory.devices[$index].service='WinUSB'
                $inventory.devices[$index].problem_code=0
                $inventory.devices[$index].reason='WinUSB installation was confirmed by Windows PnP.'
            }
        }
    } else {
        $outcome='failed'; $targets[0].status='failed'; $targets[0].reason='Windows did not confirm a working WinUSB binding after installation.'
    }
    if ($outcome -eq 'ready') {
        if (@($inventory.devices | Where-Object { $_.status -eq 'manual_required' }).Count -gt 0) {
            $outcome='manual_required'
        } elseif (@($inventory.devices | Where-Object { $_.status -eq 'reboot_required' }).Count -gt 0) {
            $outcome='reboot_required'
        }
    }
    if ($outcome -eq 'ready') { Remove-SafeStagingDirectory $helperResult.staging_dir }
    $report = [pscustomobject]@{ mode='install'; outcome=$outcome; driver_package_available=$true; driver_package_error=$null; driver_signing_model=$SigningModel; ignored_device_count=$inventory.ignored_count; devices=$inventory.devices }
    Write-SetupReport $report
    if ($outcome -eq 'reboot_required') { exit 3010 }
    if ($outcome -in @('failed','manual_required')) { exit 1 }
    exit 0
} catch {
    $failure = [pscustomobject]@{ mode=$(if($Install){'install'}else{'scan'}); outcome='failed'; error='USB driver setup failed unexpectedly. Review Windows device status and bundled driver files.'; driver_signing_model=$SigningModel; devices=@() }
    try { Write-SetupReport $failure } catch { $failure | ConvertTo-Json -Depth 8 -Compress }
    exit 1
}
